import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, path = '/admin') {
  page.setDefaultTimeout(7_000)
  await page.goto(path)
  await page.getByLabel('Пароль', { exact: true }).fill('genadi22')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Кабинет администратора', exact: true })).toBeVisible()
}

test('admin login, refresh and logout work at the direct address on a small screen', async ({ page, context }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/admin/')
  await expect(page.getByRole('heading', { name: 'Вход в кабинет' })).toBeVisible()
  await page.getByLabel('Пароль', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Неверный пароль')
  await page.getByLabel('Пароль', { exact: true }).fill('genadi22')
  await page.getByRole('button', { name: 'Показать пароль' }).click()
  await expect(page.getByLabel('Пароль', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Кабинет администратора', exact: true })).toBeVisible()
  expect((await context.cookies()).find((cookie) => cookie.name === 'nursery_admin')?.httpOnly).toBe(true)
  expect(await page.evaluate(() => document.cookie)).not.toContain('nursery_admin')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Добавить товар' })).toBeVisible()
  await page.getByRole('button', { name: 'Добавить товар' }).click()
  await expect(page.getByLabel('Название товара')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/admin-mobile-product.png', fullPage: true })
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  await page.getByRole('button', { name: 'Выйти', exact: false }).click()
  await expect(page.getByRole('heading', { name: 'Вход в кабинет' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Вход в кабинет' })).toBeVisible()
})

test('price edits, new products and articles appear for another visitor and can be hidden', async ({ page, browser }) => {
  test.setTimeout(60_000)
  const visitorContext = await browser.newContext({ baseURL: 'http://127.0.0.1:4175' })
  const visitor = await visitorContext.newPage()
  let productNumber: number | undefined
  let articleSlug: string | undefined
  await login(page)
  try {
    await page.getByLabel('Найти товар').fill('Мак пионовидный')
    await page.getByRole('button', { name: 'Изменить товар Мак пионовидный' }).click()
    await page.getByLabel('Цена, ₽', { exact: true }).fill('75')
    await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Товар сохранён')
    await visitor.goto('/#catalog')
    await visitor.getByRole('searchbox').fill('Мак пионовидный')
    await expect(visitor.locator('.plant-card')).toContainText('75 ₽')

    await page.getByRole('button', { name: 'Добавить товар' }).click()
    await page.getByLabel('Название товара').fill('Проверочное растение')
    await page.getByLabel('Цена, ₽', { exact: true }).fill('125')
    await page.getByLabel('За что указана цена').fill('Пакет, 20 семян')
    await page.getByLabel('Описание', { exact: true }).fill('Описание нового растения из питомника.')
    await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Товар сохранён')
    const content = await (await page.request.get('/site-content.json')).json()
    productNumber = content.products.find((product: { name: string }) => product.name === 'Проверочное растение').catalogNumber
    await visitor.reload()
    await visitor.getByRole('searchbox').fill('Проверочное растение')
    await expect(visitor.locator('.plant-card')).toContainText('125 ₽')

    await page.getByRole('button', { name: 'Статьи', exact: true }).click()
    await page.getByRole('button', { name: 'Добавить статью' }).click()
    await page.getByLabel('Название статьи').fill('Проверочная статья о саде')
    await page.getByLabel('Текст статьи').fill('Первый абзац с советами о саде.\n\nВторой абзац сохраняется отдельно.')
    await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Статья сохранена')
    const published = await (await page.request.get('/site-content.json')).json()
    articleSlug = published.articles.find((article: { title: string }) => article.title === 'Проверочная статья о саде').slug
    await visitor.goto('/#/articles')
    await visitor.reload()
    await visitor.getByRole('link', { name: 'Проверочная статья о саде', exact: true }).click()
    await expect(visitor.getByRole('heading', { name: 'Проверочная статья о саде', exact: true })).toBeVisible()
    await expect(visitor.locator('.article-prose')).toContainText('Второй абзац сохраняется отдельно.')

    await page.getByLabel('Найти статью').fill('Проверочная статья о саде')
    await page.getByRole('button', { name: 'Изменить статью Проверочная статья о саде' }).click()
    await page.getByLabel('Показывать статью на сайте').uncheck()
    await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Статья сохранена')
    await visitor.reload()
    await expect(visitor.getByRole('heading', { name: 'Статья не найдена' })).toBeVisible()

    await page.getByRole('button', { name: 'Товары', exact: true }).click()
    await page.getByLabel('Найти товар').fill('Проверочное растение')
    await page.getByRole('button', { name: 'Изменить товар Проверочное растение' }).click()
    await page.getByLabel('Показывать товар на сайте').uncheck()
    await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Товар сохранён')
    await visitor.goto('/#catalog')
    await visitor.reload()
    await visitor.getByRole('searchbox').fill('Проверочное растение')
    await expect(visitor.locator('.plant-card')).toHaveCount(0)
    await page.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true })
  } finally {
    const session = await (await page.request.get('/api/admin/session')).json()
    const headers = { 'X-CSRF-Token': session.csrfToken }
    await page.request.post('/api/admin/products', { headers, data: { catalogNumber: 1, price: 60 } })
    if (productNumber) await page.request.post('/api/admin/products', { headers, data: { catalogNumber: productNumber, hidden: true } })
    if (articleSlug) await page.request.post('/api/admin/article-visibility', { headers, data: { slug: articleSlug, hidden: true } })
    await visitorContext.close()
  }
})
